// The report as a self-contained HTML page (inline styles and images; prints
// to PDF from the browser) and as Markdown (images inline as data URLs).  Both
// are pure: every piece of text is escaped, and only PNG data URLs are taken
// as images.

import { parseBlocks, type Block, type Inline } from "../markdown";
import type { Report, ReportCheck, Verdict } from "./report";

const esc = (s: string): string =>
  s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;").replace(/'/g, "&#39;");

const isPng = (url: string): boolean => /^data:image\/png;base64,[A-Za-z0-9+/=]+$/.test(url);

const VERDICT_LABEL: Record<Verdict, string> = { pass: "meets its goal", attention: "needs attention", info: "not judged" };

const when = (iso: string): string => {
  const d = new Date(iso);
  return Number.isNaN(d.getTime()) ? iso : d.toLocaleString("en-GB", { dateStyle: "medium", timeStyle: "short" });
};

// ---------------------------------------------------------------- Markdown

const mdCell = (s: string): string => s.replace(/\|/g, "\\|").replace(/\n/g, " ");

function mdTable(head: string[], rows: string[][]): string {
  return [
    `| ${head.map(mdCell).join(" | ")} |`,
    `| ${head.map(() => "---").join(" | ")} |`,
    ...rows.map((r) => `| ${r.map(mdCell).join(" | ")} |`),
  ].join("\n");
}

export function reportMarkdown(r: Report): string {
  const out: string[] = [];
  out.push(`# ${r.title}`, "");
  out.push(`*${r.kind} · ${when(r.created)} · ${r.model.provider}, ${r.model.model} (${r.model.local ? "local" : "cloud"})*`, "");
  if (r.question) out.push(`> ${r.question.replace(/\n/g, " ")}`, "");

  out.push("## Quality checks", "");
  out.push(mdTable(["Check", "Verdict", "Numbers"], r.checks.map((c) => [c.title, VERDICT_LABEL[c.verdict], c.headline])), "");
  for (const c of r.checks) {
    out.push(`### ${c.title} — ${VERDICT_LABEL[c.verdict]}`, "");
    if (c.goal) out.push(`*Goal:* ${c.goal}`, "");
    out.push(mdTable(["Measure", "Value"], c.details), "");
  }

  if (r.figures.length) {
    out.push("## Figures", "");
    for (const f of r.figures) if (isPng(f.dataUrl)) out.push(`**${f.title}.** ${f.caption}`, "", `![${f.title}](${f.dataUrl})`, "");
  }

  out.push("## Dataset", "");
  out.push(mdTable(["", ""], datasetRows(r)), "");

  if (r.tuning?.length) {
    out.push("## Tuning", "");
    for (const t of r.tuning) {
      out.push(`### ${t.stage}`, "");
      out.push(mdTable(["Trial", "Changes", "Numbers", "Chosen"], t.trials.map((x) => [`#${x.n}`, x.changes, x.headline, x.chosen ? "✓" : ""])), "");
      if (t.why) out.push(`*Why:* ${t.why}`, "");
    }
  }

  if (r.steps.length) {
    out.push("## What the agent did", "");
    out.push(mdTable(["Tool", "Result"], r.steps.map((s) => [s.tool, (s.ok ? "" : "failed: ") + s.summary])), "");
  }

  out.push("## Settings used", "");
  for (const s of r.settings) out.push(`### ${s.stage}`, "", mdTable(["Setting", "Value"], s.values), "");
  if (r.sampleFacts.length) out.push("### Sample facts (set by the user)", "", mdTable(["Setting", "Value"], r.sampleFacts), "");

  if (r.narrative) out.push("## The model's summary", "", "*Written by the model; the numbers above are measured.*", "", r.narrative, "");

  out.push("## Caveats and open issues", "", ...r.caveats.map((c) => `- ${c}`), "");
  out.push("---", "", "*Generated by NEBULA3D's NEBULA Pilot. Tables and figures come from nebula3d's deterministic metrics.*", "");
  return out.join("\n");
}

const datasetRows = (r: Report): [string, string][] =>
  [
    ["Dataset", r.dataset.label],
    ["Raw file", r.dataset.rawName],
    ["Temperature", r.dataset.temperature ?? "–"],
    ["Reciprocal grid", r.dataset.grid ?? "–"],
    ["Ranges", r.dataset.ranges ?? "–"],
    ["Unit cell", r.dataset.cell ?? "–"],
    ["3D-ΔPDF grid", r.dataset.dpdfGrid ?? "–"],
    ["Stage outputs", r.dataset.stages.join(", ") || "–"],
  ] as [string, string][];

// ---------------------------------------------------------------- HTML

function inlineHtml(nodes: Inline[]): string {
  return nodes
    .map((n) => {
      switch (n.type) {
        case "text":
          return esc(n.value);
        case "strong":
          return `<strong>${inlineHtml(n.children)}</strong>`;
        case "em":
          return `<em>${inlineHtml(n.children)}</em>`;
        case "code":
          return `<code>${esc(n.value)}</code>`;
        case "link":
          return /^https?:\/\//.test(n.href) ? `<a href="${esc(n.href)}">${inlineHtml(n.children)}</a>` : inlineHtml(n.children);
      }
    })
    .join("");
}

function blocksHtml(blocks: Block[]): string {
  return blocks
    .map((b) => {
      switch (b.type) {
        case "heading":
          return `<h4>${inlineHtml(b.inline)}</h4>`;
        case "paragraph":
          return `<p>${inlineHtml(b.inline)}</p>`;
        case "code":
          return `<pre>${esc(b.value)}</pre>`;
        case "list":
          return `<${b.ordered ? "ol" : "ul"}>${b.items.map((i) => `<li>${inlineHtml(i)}</li>`).join("")}</${b.ordered ? "ol" : "ul"}>`;
        case "table":
          return `<table><thead><tr>${b.header.map((h) => `<th>${inlineHtml(h)}</th>`).join("")}</tr></thead><tbody>${b.rows
            .map((row) => `<tr>${row.map((c) => `<td>${inlineHtml(c)}</td>`).join("")}</tr>`)
            .join("")}</tbody></table>`;
        case "blockquote":
          return `<blockquote>${inlineHtml(b.inline)}</blockquote>`;
        case "hr":
          return "<hr>";
      }
    })
    .join("\n");
}

const table = (rows: [string, string][], head?: [string, string]): string =>
  `<table class="kv">${head ? `<thead><tr><th>${esc(head[0])}</th><th>${esc(head[1])}</th></tr></thead>` : ""}<tbody>${rows
    .map(([k, v]) => `<tr><th scope="row">${esc(k)}</th><td>${esc(v)}</td></tr>`)
    .join("")}</tbody></table>`;

const chip = (v: Verdict): string => `<span class="chip ${v}">${esc(VERDICT_LABEL[v])}</span>`;

const checkCard = (c: ReportCheck): string =>
  `<div class="card check"><div class="card-head"><h3>${esc(c.title)}</h3>${chip(c.verdict)}</div><p class="headline">${esc(c.headline)}</p></div>`;

const checkSection = (c: ReportCheck): string =>
  `<section class="check-detail"><div class="card-head"><h3>${esc(c.title)}</h3>${chip(c.verdict)}</div>` +
  (c.goal ? `<p class="goal"><span>Goal</span> ${esc(c.goal)}</p>` : "") +
  table(c.details, ["Measure", "Value"]) +
  "</section>";

