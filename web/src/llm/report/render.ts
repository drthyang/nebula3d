export function reportHtml(r: Report): string {
  const figures = r.figures.filter((f) => isPng(f.dataUrl));
  const parts: string[] = [];
  parts.push(`<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">`);
  parts.push(`<title>${esc(r.title)}</title><style>${STYLE}</style></head><body><main class="page">`);
  parts.push(`<div class="brand"><i></i>NEBULA3D · NEBULA Pilot report</div>`);
  parts.push(`<h1>${esc(r.dataset.label)}</h1>`);
  parts.push(
    `<p class="meta"><b>${esc(r.kind)}</b> · ${esc(when(r.created))} · ${esc(r.model.provider)}, <b>${esc(r.model.model)}</b> (${r.model.local ? "local" : "cloud"})</p>`,
  );
  if (r.question) parts.push(`<div class="request">${esc(r.question)}</div>`);

  parts.push(`<h2>Quality checks</h2><div class="grid">${r.checks.map(checkCard).join("")}</div>`);

  if (figures.length) {
    parts.push(
      `<h2>Figures</h2><div class="figures">${figures
        .map((f) => `<figure><img src="${f.dataUrl}" alt="${esc(f.title)}"><figcaption><b>${esc(f.title)}.</b> ${esc(f.caption)}</figcaption></figure>`)
        .join("")}</div>`,
    );
  }

  parts.push(`<h2>The checks in detail</h2>${r.checks.map(checkSection).join("")}`);
  parts.push(`<h2>Dataset</h2>${table(datasetRows(r))}`);

  if (r.tuning?.length) {
    parts.push("<h2>Tuning</h2>");
    for (const t of r.tuning) {
      parts.push(`<h4>${esc(t.stage)}</h4><table><thead><tr><th>Trial</th><th>Changes</th><th>Numbers</th><th>Chosen</th></tr></thead><tbody>`);
      parts.push(t.trials.map((x) => `<tr><td>#${x.n}</td><td>${esc(x.changes)}</td><td>${esc(x.headline)}</td><td>${x.chosen ? "✓" : ""}</td></tr>`).join(""));
      parts.push(`</tbody></table>${t.why ? `<p class="why">${esc(t.why)}</p>` : ""}`);
    }
  }

  if (r.steps.length) {
    parts.push(
      `<h2>What the agent did</h2><table><thead><tr><th>Tool</th><th>Result</th></tr></thead><tbody>${r.steps
        .map((s) => `<tr><td><code>${esc(s.tool)}</code></td><td>${s.ok ? "" : "<b>failed:</b> "}${esc(s.summary)}</td></tr>`)
        .join("")}</tbody></table>`,
    );
  }

  parts.push(`<h2>Settings used</h2><div class="grid">`);
  for (const s of r.settings) parts.push(`<div class="card"><h3>${esc(s.stage)}</h3>${table(s.values)}</div>`);
  if (r.sampleFacts.length) parts.push(`<div class="card"><h3>Sample facts (set by the user)</h3>${table(r.sampleFacts)}</div>`);
  parts.push("</div>");

  if (r.narrative) {
    parts.push(`<h2>The model's summary</h2><p class="note">Written by the model; the numbers above are measured.</p>`);
    parts.push(`<div class="narrative">${blocksHtml(parseBlocks(r.narrative))}</div>`);
  }

  parts.push(`<h2>Caveats and open issues</h2><ul class="caveats">${r.caveats.map((c) => `<li>${esc(c)}</li>`).join("")}</ul>`);
  parts.push(
    `<footer>Generated by NEBULA3D's NEBULA Pilot on ${esc(when(r.created))}. Tables and figures come from nebula3d's deterministic metrics; the summary is the model's.</footer>`,
  );
  parts.push("</main></body></html>");
  return parts.join("\n");
}
